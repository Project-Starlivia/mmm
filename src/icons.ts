export type IconName = keyof typeof MARKS;

/** 線ではなく面で塗る絵。**よそのロゴだけ** — 自前の絵は全部線で揃える
 *  という約束（一番上のコメント）は変えず、例外だとここに書いて言い切る */
const FILLED: ReadonlySet<IconName> = new Set(["mark-github"]);

/**
 * **動きを持つ絵と、その動きの名前。** ここに載せた印は状態ではなく
 * **出来事**か**最中**を言うもので、止まった姿だけでは意味が半分落ちる
 * （いつからそこに在るのか / いま動いているのかが読めない）。
 * 動きそのものは CSS 側（`.icon.drawn` / `.icon.spun`）が持つ。
 */
const MOTION: ReadonlyMap<IconName, string> = new Map([
  ["check", "drawn"], // 引かれながら出る = 済んだ
  ["loader-circle", "spun"], // 回り続ける = まだ走っている
]);

/** その名前の絵。**塗りではなく線**で引く（Lucide の流儀のまま） */
export function icon(name: IconName): SVGSVGElement {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  const motion = MOTION.get(name);
  svg.setAttribute("class", motion ? `icon ${motion}` : "icon");
  svg.setAttribute("viewBox", `0 0 ${BOX} ${BOX}`);
  svg.setAttribute("aria-hidden", "true");
  if (FILLED.has(name)) {
    svg.setAttribute("fill", "currentColor");
  } else {
    svg.setAttribute("fill", "none");
    svg.setAttribute("stroke", "currentColor");
    svg.setAttribute("stroke-width", "2");
    svg.setAttribute("stroke-linecap", "round");
    svg.setAttribute("stroke-linejoin", "round");
  }
  // 中身は固定の文字列（このファイル以外からは決して渡らない）。
  // 子ごとに path/circle/rect/line が入り混じるので、要素を 1 つずつ
  // 組み立てるより、Lucide の中身をそのまま挿す
  svg.innerHTML = MARKS[name];
  return svg;
}

/** 絵と文字を並べたボタンの中身にする（絵が先か後かは呼ぶ側が決める） */
export function label(text: string, name: IconName, after = false): Node[] {
  const span = document.createElement("span");
  span.textContent = text;
  return after ? [span, icon(name)] : [icon(name), span];
}

/** ぐるぐるを出すまでの間。**ここを過ぎて初めて「待たされている」**
 *  — 大半の一手はこれより速く終わり、出してすぐ消せば点滅にしかならない */
const WAIT = 200;

/**
 * 押した場所で答える。**走っているあいだ回し、済んだらチェックを引く。**
 *
 * 印の出し入れをここ 1 か所に置くのは、「押した場所が答える」という同じ
 * 話をメニューの行とヘッダのボタンが別々に書かないため。`put` は
 * **その絵をいまの場所に出す**ことだけを知っていればよい（行なら頭の絵を
 * 差し替え、ボタンなら字と並べ直す）。
 *
 * しくじったら何も出さない — 嘘の頷きを返さない。戻す係は呼ぶ側
 * （行は建て直され、ボタンはいまの出し方に戻る）。
 */
export async function nod(
  work: Promise<boolean>,
  put: (name: IconName) => void,
): Promise<boolean> {
  const spin = setTimeout(() => put("loader-circle"), WAIT);
  const ok = await work;
  clearTimeout(spin);
  if (ok) put("check");
  return ok;
}
