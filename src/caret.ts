// md のカーソルが、いまどのノードに居るか。DOM も文書の意味も知らない、
// 区間の当てはめだけの層。
//
// ノードは [from, to) の区間で、入れ子はそのまま区間の入れ子になる。だから
// 「その位置を含む、いちばん内側のノード」はいつも 1 つに決まる。区間は
// コアが渡してくるものをそのまま読む — どこからどこまでが 1 ノードかを
// ここで数え直さない。

import type { NodeInfo } from "./coreApi.ts";

/**
 * `offset` を含む、いちばん内側のノードの id。どのノードにも属さない位置
 * （文書の頭・最初の見出しより前）では -1。
 *
 * **閉じ際（`offset === to`）も中と見なす。** 区間そのものは `[from, to)`
 * だが、カーソルはその位置に**立てる**（文字と文字の隙間にある）。半開で
 * 読むと、文書の末尾では全部の区間が閉じきっていて何も指せない —
 * 追記しているあいだじゅう印が出ない、といういちばん困る形になる。
 * 境界で 2 つが並ぶときは後から始まったほうが勝つので、兄弟の継ぎ目
 * （`A.to === B.from`）では手前の A ではなく B を指す。
 *
 * `nodes` は文書順（= `from` の昇順）。まず「`from` が `offset` 以下」の
 * 最後のノードを二分探索で当て、そこから前へ遡って**最初に `offset` まで
 * 届いているもの**を採る。遡りながら捨てているのは先に閉じた区間で、
 * それより内側のものは（後から始まるので）二分探索の時点で越えている —
 * だから最初に見つかった 1 つがいちばん内側になる。
 */
export function caretNode(nodes: NodeInfo[], offset: number): number {
  let lo = 0;
  let hi = nodes.length - 1;
  let at = -1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (nodes[mid].from <= offset) {
      at = mid;
      lo = mid + 1;
    } else {
      hi = mid - 1;
    }
  }
  for (let i = at; i >= 0; i--) {
    if (nodes[i].to >= offset) return nodes[i].id;
  }
  return -1;
}
